import { test, expect } from "@playwright/test";
test("vault forms stay visible, browsing supports cancel and errors, and location persists", async ({ page, request }) => {
  await request.post('/api/vaults/create-location', { data: { path: "" } });
  await page.goto('/'); await page.locator('.workspace-switch').click();
  const dialog = page.locator('.vault-manager-dialog');
  const createPath = dialog.getByLabel("Save location", { exact: true });
  const openPath = dialog.getByLabel("Existing vault folder", { exact: true });
  await expect(dialog.locator('[aria-current="true"]')).toBeDisabled();
  await expect(dialog.locator('[data-vault-create]')).toBeVisible();
  await expect(dialog.locator('[data-vault-open]')).toBeVisible();
  await expect(dialog.locator('details')).toHaveCount(0);
  await expect(createPath).toHaveValue("");
  await expect(dialog.locator('[data-browse="open"]')).toBeVisible();
  await expect(dialog.locator(".vault-entry-icon svg").first()).toBeVisible();
  await dialog.locator('[data-vault-create] input[name="name"]').fill('Research');
  let selected: string | null = "C:\\Notes 中文";
  await page.route('**/api/vaults/browse', route => route.fulfill({ json: { path: selected } }));
  await dialog.locator('[data-browse="create"]').click();
  await expect(createPath).toHaveValue(selected);
  await expect(dialog.locator('[data-preview]')).toHaveText(selected + "\\Research");
  await expect(dialog.locator('[data-browse="create"]')).toBeEnabled();
  selected = null;
  await dialog.locator('[data-browse="create"]').click();
  await expect(dialog.locator('[data-browse="create"]')).toBeEnabled();
  await expect(createPath).toHaveValue("C:\\Notes 中文");
  selected = "C:\\Notes 中文\\Existing";
  await dialog.locator('[data-browse="open"]').click();
  await expect(openPath).toHaveValue(selected);
  await expect(dialog.locator('[data-browse="open"]')).toBeEnabled();
  await dialog.screenshot({ path: '.run/logs/vault-redesign-web.png' });
  await createPath.fill("D:\\Research notes");
  await page.keyboard.press("Escape");
  await expect.poll(async () => (await (await request.get('/api/vaults')).json()).createLocation).toBe("D:\\Research notes");
  await page.reload(); await page.locator('.workspace-switch').click();
  await expect(createPath).toHaveValue("D:\\Research notes");
  await page.route('**/api/vaults/browse', route => route.fulfill({ status: 500, json: { error: "Picker unavailable" } }));
  await dialog.locator('[data-browse="open"]').click();
  await expect(dialog.locator('[data-vault-message]')).toHaveText("Picker unavailable");
  await expect(dialog.locator('[data-browse="open"]')).toBeEnabled();
  await expect(createPath).toHaveValue("D:\\Research notes");
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(dialog.locator('[data-vault-create]')).toBeVisible();
  await expect(dialog.locator('[data-vault-open]')).toBeVisible();
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await dialog.locator('[data-browse="open"]').scrollIntoViewIfNeeded();
  await expect(dialog.locator('[data-browse="open"]')).toBeInViewport();
  await page.screenshot({ path: '.run/logs/vault-redesign-narrow.png' });
  await request.post('/api/vaults/create-location', { data: { path: "" } });
});
