import { test, expect, type Page, type APIRequestContext } from "@playwright/test";
import { expectSource } from "./source-helper";

async function open(page: Page, request: APIRequestContext, body = "") {
  const response = await request.post("/api/pages", { data: { title: "People interactions", body, bodyFormat: "notion-markdown", syntax: { version: 1, variant: "notdown", extensions: {} } } });
  expect(response.status()).toBe(201);
  const note = await response.json();
  await page.goto(`/#page/${note.id}`);
  await page.getByRole("button", { name: "Page", exact: true }).click();
  await expect(page.locator(".pm-document")).toBeVisible();
  return note;
}
async function createPerson(request: APIRequestContext, name: string, organization = "") {
  const response = await request.post("/api/people", { data: { name, organization } });
  expect(response.status()).toBe(201);
  return response.json();
}
const peopleDialog = (page: Page) => page.getByRole("dialog", { name: "People", exact: true });

test("People CRUD, search, @ keyboard mention, live rename, delete and restore survive reload", async ({ page, request }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  const note = await open(page, request);
  await page.getByRole("button", { name: "People", exact: true }).click();
  const dialog = peopleDialog(page);
  await dialog.getByRole("button", { name: "New person" }).click();
  await dialog.getByLabel("Name *", { exact: true }).fill("Eric People E2E");
  await dialog.getByLabel("Email", { exact: true }).fill("eric.people@example.test");
  await dialog.getByLabel("Phone", { exact: true }).fill("+86 1234567");
  await dialog.getByLabel("Organization").fill("Product studio");
  await dialog.getByLabel("Notes", { exact: true }).fill("Met at the design workshop.\nFollow up next month.");
  await dialog.getByRole("button", { name: "Save person", exact: true }).click();
  await expect(dialog.getByRole("status")).toHaveText("Saved locally");
  const person = (await (await request.get("/api/people")).json()).find((person: any) => person.name === "Eric People E2E");
  expect(person.notes).toContain("Follow up next month.");
  await dialog.getByRole("searchbox", { name: "Search people" }).fill("no contact matches");
  await expect(dialog.getByRole("list")).toContainText("No people match");
  await dialog.getByRole("searchbox", { name: "Search people" }).fill("product eric");
  await expect(dialog.locator("[data-person]")).toHaveCount(1);
  await page.screenshot({ path: "test-results/people-directory.png" });
  await dialog.getByRole("button", { name: "Close people" }).click();
  await page.locator(".pm-document").click();
  await page.keyboard.type("Discuss with @Eric People");
  const menu = page.getByRole("listbox", { name: "Mention suggestions" });
  await expect(menu.getByRole("option", { name: /Eric People E2E/ })).toBeVisible();
  await page.screenshot({ path: "test-results/people-mention.png" });
  await page.keyboard.press("ArrowDown");
  await page.keyboard.press("Enter");
  const chip = page.locator(".pm-person-mention");
  await expect(chip).toHaveText("@Eric People E2E");
  await page.keyboard.type(" tomorrow.");
  await page.keyboard.press("Control+s");
  await expect.poll(async () => (await (await request.get(`/api/pages/${note.id}`)).json()).body).toContain(`person://${person.id}`);
  const savedBody = (await (await request.get(`/api/pages/${note.id}`)).json()).body;
  await chip.click();
  await dialog.getByLabel("Name *", { exact: true }).fill("Eric Renamed E2E");
  await dialog.getByRole("button", { name: "Save person", exact: true }).click();
  await expect(dialog.getByRole("status")).toHaveText("Saved locally");
  await dialog.getByRole("button", { name: "Close people" }).click();
  await expect(chip).toHaveText("@Eric Renamed E2E");
  expect((await (await request.get(`/api/pages/${note.id}`)).json()).body).toBe(savedBody);
  await chip.click();
  await dialog.getByRole("button", { name: "Delete person", exact: true }).click();
  await expect(dialog.getByRole("status")).toContainText("Person deleted");
  await dialog.getByRole("button", { name: "Close people" }).click();
  await expect(chip).toHaveClass(/person-deleted/);
  await page.reload();
  await expect(chip).toHaveText("@Eric Renamed E2E");
  await expect(chip).toHaveClass(/person-deleted/);
  await chip.click();
  await dialog.getByRole("button", { name: "Restore person", exact: true }).click();
  await expect(dialog.getByRole("status")).toHaveText("Saved locally");
  await dialog.getByRole("button", { name: "Close people" }).click();
  await expect(chip).not.toHaveClass(/person-deleted/);
  expect(errors).toEqual([]);
});

test("@ person completion supports undo, duplicate-name disambiguation, escape, dates, and code boundaries", async ({ page, request }) => {
  const person = await createPerson(request, "Shared Person E2E", "Alpha studio");
  await createPerson(request, "Shared Person E2E", "Beta studio");
  await open(page, request);
  const editor = page.locator(".pm-document");
  await editor.click();
  await page.keyboard.type("@Shared Person");
  const menu = page.getByRole("listbox", { name: "Mention suggestions" });
  await expect(menu.locator("[data-person-id]")).toHaveCount(2);
  await menu.getByRole("option", { name: /Alpha studio/ }).click();
  await expect(page.locator(".pm-person-mention")).toHaveAttribute("data-person-id", person.id);
  await page.keyboard.press("Control+z");
  await expect(page.locator(".pm-person-mention")).toHaveCount(0);
  await expect(editor).toContainText("@Shared Person");
  await page.keyboard.press("Control+Shift+z");
  await expect(page.locator(".pm-person-mention")).toHaveCount(1);
  await page.keyboard.type(" @today");
  await page.keyboard.press("Enter");
  await expect(page.locator(".pm-date-mention")).toHaveCount(1);
  await page.keyboard.type(" @Shared Person");
  await page.keyboard.press("Escape");
  await expect(menu).toHaveCount(0);
  await page.keyboard.type(" literal");
  await expect(editor).toContainText("@Shared Person literal");
  await page.keyboard.press("Control+e");
  await expectSource(page, new RegExp(`person://${person.id}`));
  await expect(menu).toHaveCount(0);
  await open(page, request, "```text\ncode\n```\n\n`inline`\n\nEmail user@example.test");
  await editor.locator("pre").click();
  await page.keyboard.press("End");
  await page.keyboard.type(" @Shared Person");
  await expect(menu).toHaveCount(0);
  await editor.locator("p").filter({ has: page.locator("code") }).click();
  await page.keyboard.press("End");
  await page.keyboard.type(" @Shared Person");
  await expect(menu).toHaveCount(0);
});

