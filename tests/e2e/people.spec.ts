test("narrow People form keeps unsaved drafts when switching contacts and closing; split-view mentions stay safe", async ({ page, request }) => {
  const a = await createPerson(request, '蔡 <Eric> & "Studio"', "Narrow contact A");
  const b = await createPerson(request, "Narrow contact B");
  await open(page, request);
  await page.setViewportSize({ width: 420, height: 740 });
  await page.getByRole("button", { name: "Toggle sidebar" }).click();
  await page.getByRole("button", { name: "People", exact: true }).click();
  const dialog = peopleDialog(page);
  await dialog.getByRole("searchbox", { name: "Search people" }).fill("Narrow contact A");
  await dialog.locator(`[data-person="${a.id}"]`).click();
  const bounds = (await dialog.boundingBox())!;
  expect(bounds.x).toBeGreaterThanOrEqual(8);
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(412);
  await dialog.getByLabel("Notes", { exact: true }).fill("Keep this window's draft");
  await dialog.getByRole("searchbox", { name: "Search people" }).fill("Narrow contact B");
  await dialog.locator(`[data-person="${b.id}"]`).click();
  await dialog.getByRole("searchbox", { name: "Search people" }).fill("Narrow contact A");
  await dialog.locator(`[data-person="${a.id}"]`).click();
  await expect(dialog.getByLabel("Notes", { exact: true })).toHaveValue("Keep this window's draft");
  await page.screenshot({ path: "test-results/people-narrow.png" });
  await dialog.getByRole("button", { name: "Close people" }).click();
  await page.getByRole("button", { name: "People", exact: true }).click();
  await dialog.getByRole("searchbox", { name: "Search people" }).fill("Narrow contact A");
  await dialog.locator(`[data-person="${a.id}"]`).click();
  await expect(dialog.getByLabel("Notes", { exact: true })).toHaveValue("Keep this window's draft");
  await dialog.getByRole("button", { name: "Save person", exact: true }).click();
  await expect(dialog.getByRole("status")).toHaveText("Saved locally");
  await dialog.getByRole("button", { name: "Close people" }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole("button", { name: "Split", exact: true }).click();
  await page.locator(".pm-document").click();
  await page.keyboard.type("@");
  await page.keyboard.insertText("蔡");
  await page.getByRole("option", { name: /Narrow contact A/ }).click();
  await expect(page.locator(".pm-person-mention")).toHaveText('@蔡 <Eric> & "Studio"');
  await expectSource(page, /&lt;Eric&gt;/);
  await expect(page.locator(".pm-person-mention eric")).toHaveCount(0);
});
