import { test, expect } from "@playwright/test";
import { statusDatabase, statusRecords } from "../unit/notion-status-fixture";
import { stablePageUuid } from "../../src/vault/page-id";

test("imported Status pills differ from Select; blank cells stay blank and property icons survive editing and reload", async ({ page, request }, info) => {
  const response = await request.post("/api/notion/import/preview", { data: { token: "test-only-status-token", pageId: statusDatabase } });
  expect(response.ok()).toBeTruthy(); const preview = await response.json();
  expect((await request.post("/api/import/commit", { data: { id: preview.id } })).ok()).toBeTruthy();
  const local = (id: string) => stablePageUuid(`notion-${preview.id.slice(0, 24)}-${id}`), dbId = local(statusDatabase);
  const snapshot = await (await request.get(`/api/databases/${dbId}`)).json(), source = snapshot.dataSources[0];
  const status = source.properties.find((field: any) => field.name === "Status"), select = source.properties.find((field: any) => field.name === "Class"), date = source.properties.find((field: any) => field.name === "Dates");
  expect(status.type).toBe("status"); expect(select.type).toBe("select");
  await page.goto(`/#database/${dbId}`);
  const first = page.locator(`tr[data-page-id="${local(statusRecords[0])}"]`), empty = page.locator(`tr[data-page-id="${local(statusRecords[1])}"]`);
  const pill = first.locator('td[data-type="status"] .database-tag');
  await expect(pill).toHaveClass(/database-status-tag/); await expect(pill).toHaveText("In progress");
  expect(await pill.evaluate(el => ({ radius: getComputedStyle(el).borderRadius, dot: getComputedStyle(el, "::before").width }))).toEqual({ radius: "999px", dot: "8px" });
  await expect(first.locator('td[data-type="select"] .database-tag')).not.toHaveClass(/database-status-tag/);
  await expect(empty.locator('td[data-type="status"] button')).toHaveText("");
  await expect(empty.locator('td[data-type="select"] button')).toHaveText("");
  await expect(empty.locator('td[data-type="files"]')).toHaveText("");
  const blankDate = page.getByLabel("Dates: Empty record", { exact: true });
  expect(await blankDate.evaluate(el => getComputedStyle(el, "::placeholder").color)).toBe("rgba(0, 0, 0, 0)");
  await expect(page.getByLabel("End Dates: Empty record", { exact: true })).toBeHidden();
  await page.screenshot({ path: info.outputPath("status-pills-and-blank-cells.png"), fullPage: true });

  await page.getByLabel("Status: First", { exact: true }).click();
  await page.getByRole("option", { name: "Done", exact: true }).click();
  await expect(pill).toHaveText("Done"); await expect(pill).toHaveAttribute("data-color", "green");
  await blankDate.fill("2026-11-15");
  await page.getByLabel("End Dates: Empty record", { exact: true }).fill("2026-11-16");
  await page.getByRole("button", { name: "Edit Status property", exact: true }).click();
  const settings = page.getByRole("dialog", { name: "Property settings", exact: true });
  await settings.getByRole("button", { name: "Property icon", exact: true }).click();
  const picker = page.getByRole("dialog", { name: "Property icon", exact: true });
  await picker.getByLabel("Search icons", { exact: true }).fill("plane");
  await picker.getByRole("button", { name: "plane", exact: true }).click();
  await settings.getByRole("button", { name: "Save property", exact: true }).click();
  await expect(page.locator('th[data-type="status"] [data-property-icon="plane"]')).toBeVisible();
  await page.reload();
  await expect(page.locator('th[data-type="status"] [data-property-icon="plane"]')).toBeVisible();
  await expect(pill).toHaveText("Done");
  await expect(blankDate).toHaveValue("2026-11-15");
  await expect(page.getByLabel("End Dates: Empty record", { exact: true })).toHaveValue("2026-11-16");
  const saved = await (await request.get(`/api/databases/${dbId}`)).json();
  expect(saved.dataSources[0].properties.find((field: any) => field.id === status.id)).toMatchObject({ type: "status", icon: "plane", options: status.options, notion: status.notion });
  expect(saved.pages.find((record: any) => record.id === local(statusRecords[0])).properties[status.key]).toBe("done");
  expect(saved.pages.find((record: any) => record.id === local(statusRecords[1])).properties[date.key]).toMatchObject({ start: "2026-11-15", end: "2026-11-16" });
  await page.getByLabel("Name: First", { exact: true }).hover();
  await page.getByRole("button", { name: "Open First", exact: true }).click();
  await expect(page.locator('.database-peek-property [data-property-icon="plane"]')).toBeVisible();
  await page.getByRole("button", { name: "Close record", exact: true }).click();
  await page.getByRole("button", { name: "Edit Status property", exact: true }).click();
  await settings.getByRole("button", { name: "Property icon", exact: true }).click();
  await picker.getByRole("button", { name: "Use default icon", exact: true }).click();
  await settings.getByRole("button", { name: "Save property", exact: true }).click();
  await expect(page.locator('th[data-type="status"] [data-property-icon="loader"]')).toBeVisible();
  await page.getByRole("button", { name: "View settings", exact: true }).click();
  const viewSettings = page.getByRole("dialog", { name: "View settings", exact: true });
  await viewSettings.getByRole("button", { name: "View icon", exact: true }).click();
  const viewPicker = page.getByRole("dialog", { name: "View icon", exact: true });
  await viewPicker.getByLabel("Search icons", { exact: true }).fill("star");
  await viewPicker.getByRole("button", { name: "star", exact: true }).click();
  await viewSettings.getByRole("button", { name: "Close", exact: true }).click();
  await page.reload();
  await expect(page.locator('.database-view-tabs [data-view-icon="star"]')).toBeVisible();
  await expect(page.locator('th[data-type="status"] [data-property-icon="loader"]')).toBeVisible();
});
