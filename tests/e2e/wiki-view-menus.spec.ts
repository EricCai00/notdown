import { test, expect, type Page } from "@playwright/test";
import { createBlockDatabase } from "./database-fixture";

const options = (page: Page) => page.getByRole("dialog", { name: "View options", exact: true });
async function openOptions(page: Page, name: string) {
  await page.locator(".wiki-view-trigger").click();
  await page.getByRole("button", { name: `${name} view options`, exact: true }).click();
  await expect(options(page)).toBeVisible();
}

for (const home of [true, false]) test(`Wiki ${home ? "Home" : "collection"} offers nested view actions without selecting the target`, async ({ page, request, context }, info) => {
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  const created = await (await request.post("/api/databases", { data: { title: "Wiki menu", kind: "wiki" } })).json();
  const added = await (await request.post(`/api/databases/${created.database.id}/views`, { data: { baseRevision: created.database.revision, name: "Other view", type: "table", dataSourceId: created.dataSources[0].id } })).json();
  const view = added.views.find((view: any) => view.name === "Other view");
  await page.goto(home ? `/#page/${created.hostPage.id}` : `/#database/${created.database.id}?view=${created.views[0].id}`);
  const selected = home ? "Home" : "All pages";
  await expect(page.locator(".wiki-view-trigger")).toHaveText(selected);
  if (home) await page.locator(".pm-document").fill("Pending Home survives view actions");
  await openOptions(page, "Other view");
  await expect(page.locator(".wiki-view-menu")).toBeVisible();
  await expect(page.locator(".wiki-view-trigger")).toHaveText(selected);
  await expect(options(page).locator(":scope > button, :scope > div > button")).toHaveText(["Rename", "View icon", "Edit view", "Copy link to view", "Duplicate view", "Delete view"]);
  await page.screenshot({ path: info.outputPath(`wiki-${home ? "home" : "collection"}-view-options.png`) });
  await options(page).getByRole("button", { name: "Copy link to view", exact: true }).click();
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toContain(`#database/${created.database.id}?view=${view.id}`);
  await page.keyboard.press("Escape");
  await expect(options(page)).toHaveCount(0);
  await expect(page.locator(".wiki-view-menu")).toBeVisible();
  await expect(page.getByRole("button", { name: "Other view view options", exact: true })).toBeFocused();
  await expect(page.locator("#main")).toHaveClass(/database-scroll-locked/);
  await page.getByRole("button", { name: "Other view view options", exact: true }).click();
  await options(page).getByRole("button", { name: "Rename", exact: true }).click();
  await page.getByLabel("View name", { exact: true }).fill("Renamed view");
  await page.getByRole("button", { name: "Save view", exact: true }).click();
  await expect(page.locator(".wiki-view-menu")).toHaveCount(0);
  await expect(page.locator(".wiki-view-trigger")).toHaveText(selected);
  await openOptions(page, "Renamed view");
  await options(page).getByRole("button", { name: "View icon", exact: true }).click();
  await page.getByRole("textbox", { name: "Search icons", exact: true }).fill("microscope");
  await page.getByRole("button", { name: "microscope", exact: true }).click();
  await page.locator(".wiki-view-trigger").click();
  await expect(options(page)).toHaveCount(0);
  await expect(page.locator(".wiki-view-trigger")).toHaveText(selected);
  const withIcon = await (await request.get(`/api/databases/${created.database.id}`)).json();
  expect(withIcon.views.find((item: any) => item.id === view.id).icon).toBe("microscope");
  await openOptions(page, "Renamed view");
  await options(page).getByRole("button", { name: "Duplicate view", exact: true }).click();
  await expect(options(page)).toHaveCount(0);
  const duplicated = await (await request.get(`/api/databases/${created.database.id}`)).json();
  expect(duplicated.views.find((item: any) => item.name === "Renamed view (copy)").icon).toBe("microscope");
  await openOptions(page, "Renamed view (copy)");
  await options(page).getByRole("button", { name: "Delete view", exact: true }).click();
  await expect(options(page)).toHaveCount(0);
  const saved = await (await request.get(`/api/databases/${created.database.id}`)).json();
  expect(saved.views.map((item: any) => item.name)).toEqual(["All pages", "Renamed view"]);
  expect(saved.views.find((item: any) => item.id === view.id).name).toBe("Renamed view");
  if (home) expect((await (await request.get(`/api/pages/${created.hostPage.id}`)).json()).body).toContain("Pending Home survives view actions");
  await openOptions(page, "Renamed view");
  await options(page).getByRole("button", { name: "Edit view", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "View settings", exact: true })).toBeVisible();
  await expect(page.getByLabel("View name", { exact: true })).toHaveValue("Renamed view");
  await page.keyboard.press("Escape");
  await expect(page.locator(".database-scroll-locked")).toHaveCount(0);
});

test("Wiki view rename conflicts preserve the draft and keep background scrolling locked", async ({ page, request }) => {
  const snapshot = await (await request.post("/api/databases", { data: { title: "Conflict wiki", kind: "wiki" } })).json();
  await page.goto(`/#page/${snapshot.hostPage.id}`);
  await openOptions(page, "All pages");
  await options(page).getByRole("button", { name: "Rename", exact: true }).click();
  await page.getByLabel("View name", { exact: true }).fill("Local name");
  const view = snapshot.views[0];
  expect((await request.put(`/api/database-views/${view.id}`, { data: { baseRevision: view.revision, name: "External name" } })).ok()).toBeTruthy();
  await page.getByRole("button", { name: "Save view", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "Rename view", exact: true }).getByRole("status")).toContainText(/changed/i);
  await expect(page.getByLabel("View name", { exact: true })).toHaveValue("Local name");
  await expect(page.locator("#main")).toHaveClass(/database-scroll-locked/);
  await page.getByRole("button", { name: "Databases", exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`#page/${snapshot.hostPage.id}$`));
  await expect(page.getByLabel("View name", { exact: true })).toHaveValue("Local name");
  await page.getByRole("button", { name: "Discard menu changes", exact: true }).click();
  await expect(page.locator(".database-scroll-locked")).toHaveCount(0);
  expect((await (await request.get(`/api/databases/${snapshot.database.id}`)).json()).views[0].name).toBe("External name");
});

test("database settings lock vertical and horizontal background scrolling but allow internal menu scrolling", async ({ page, request }, info) => {
  const fixture = await createBlockDatabase(request);
  await page.setViewportSize({ width: 1000, height: 650 });
  await page.goto(`/#database/${fixture.database.id}`);
  const pane = page.locator(".database-table-pane"), table = page.locator(".database-table-scroll");
  expect(await pane.evaluate(el => el.scrollHeight > el.clientHeight)).toBe(true);
  expect(await table.evaluate(el => el.scrollWidth > el.clientWidth)).toBe(true);
  const anchorBefore = await page.getByRole("button", { name: "View settings", exact: true }).boundingBox();
  await page.getByRole("button", { name: "View settings", exact: true }).click();
  expect(await page.getByRole("button", { name: "View settings", exact: true }).boundingBox()).toEqual(anchorBefore);
  const menu = page.getByRole("dialog", { name: "View settings", exact: true });
  const before = await pane.evaluate(el => ({ top: el.scrollTop, left: el.scrollLeft }));
  const xBefore = await table.evaluate(el => el.scrollLeft);
  await page.mouse.move(400, 400); await page.mouse.wheel(600, 600);
  await expect.poll(() => pane.evaluate(el => ({ top: el.scrollTop, left: el.scrollLeft }))).toEqual(before);
  await expect.poll(() => table.evaluate(el => el.scrollLeft)).toBe(xBefore);
  await pane.press("PageDown");
  await expect.poll(() => pane.evaluate(el => el.scrollTop)).toBe(before.top);
  await menu.hover(); await page.mouse.wheel(0, 500);
  await expect.poll(() => menu.evaluate(el => el.scrollTop)).toBeGreaterThan(0);
  await page.screenshot({ path: info.outputPath("settings-internal-scroll.png") });
  await page.keyboard.press("Escape");
  await expect(page.locator(".database-scroll-locked")).toHaveCount(0);
  await page.mouse.move(400, 400); await page.mouse.wheel(0, 500);
  await expect.poll(() => pane.evaluate(el => el.scrollTop)).toBeGreaterThan(before.top);
  await page.mouse.wheel(500, 0);
  await expect.poll(() => table.evaluate(el => el.scrollLeft)).toBeGreaterThan(xBefore);
});
