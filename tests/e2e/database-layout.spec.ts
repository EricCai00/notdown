import { test, expect, type APIRequestContext } from "@playwright/test";
const post = async (request: APIRequestContext, url: string, data: unknown) => { const response = await request.post(url, { data }); expect(response.ok(), await response.text()).toBeTruthy(); return response.json(); };

test("right settings replace their contents with compact source rows and return without creating cancelled input", async ({ page, request }, info) => {
  let db = await post(request, "/api/databases", { title: "Data source 1 and 2" });
  db = await post(request, `/api/databases/${db.database.id}/data-sources`, { title: "Data source 2", baseRevision: db.database.revision });
  const owner = await post(request, "/api/databases", { title: "Shared records" });
  db = await post(request, `/api/databases/${db.database.id}/data-sources/link`, { dataSourceId: owner.dataSources[0].id, sourceRevision: owner.dataSources[0].revision, baseRevision: db.database.revision });
  await page.goto(`/#database/${db.database.id}`);
  await page.getByRole("button", { name: "View settings", exact: true }).click();
  const settings = page.getByRole("dialog", { name: "View settings", exact: true }), initial = (await settings.boundingBox())!;
  await expect(settings).toHaveCSS("box-shadow", "none");
  await page.screenshot({ path: info.outputPath("view-settings.png") });
  await settings.getByLabel("View name", { exact: true }).fill("Saved before sources");
  await settings.getByRole("button", { name: "Manage data sources", exact: true }).click();
  const manager = page.getByRole("dialog", { name: "Manage data sources", exact: true });
  await expect(settings).toBeHidden(); await expect(manager).toBeVisible();
  const bounds = (await manager.boundingBox())!;
  expect(bounds.x).toBeCloseTo(initial.x, 0); expect(bounds.y).toBeCloseTo(initial.y, 0);
  expect(bounds.width).toBe(300); expect(bounds.x).toBeGreaterThan(900);
  await expect(manager.locator(".database-source-menu-item")).toHaveCount(3);
  await expect(manager.locator(".database-source-description")).toHaveText(["1 view", "1 view", "1 view"]);
  await page.screenshot({ path: info.outputPath("manage-sources.png") });
  await manager.getByRole("button", { name: "Add data source", exact: true }).click();
  const create = page.getByRole("dialog", { name: "New data source", exact: true });
  await create.getByLabel("Data source name", { exact: true }).fill("Must stay cancelled");
  await create.getByRole("button", { name: "Back", exact: true }).click();
  await manager.getByRole("button", { name: "Back", exact: true }).click();
  await expect(settings).toBeVisible();
  await settings.getByLabel("View name", { exact: true }).fill("Saved after sources");
  await settings.getByRole("button", { name: "Save view", exact: true }).click();
  await expect(page.locator(".database-popover")).toHaveCount(0);
  const saved = await (await request.get(`/api/databases/${db.database.id}`)).json();
  expect(saved.dataSources.map((source: any) => source.title)).not.toContain("Must stay cancelled");
  expect(saved.views[0].name).toBe("Saved after sources");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "View settings", exact: true }).click();
  await settings.getByRole("button", { name: "Manage data sources", exact: true }).click();
  const narrow = (await manager.boundingBox())!;
  expect(narrow.x).toBeGreaterThanOrEqual(0); expect(narrow.x + narrow.width).toBeLessThanOrEqual(390);
  await manager.getByRole("button", { name: "Close", exact: true }).click();
  await expect(page.locator(".database-popover")).toHaveCount(0);
});

test("view tabs open their own dropdown and rename, display, duplicate and delete persist without copying records", async ({ page, request }, info) => {
  const db = await post(request, "/api/databases", { title: "View dropdown" }), source = db.dataSources[0];
  const row = await post(request, `/api/data-sources/${source.id}/records`, { title: "Shared page", baseRevision: source.revision });
  await page.goto(`/#database/${db.database.id}`);
  const tab = page.getByRole("tab", { name: "Table", exact: true }); await tab.click();
  const menu = page.getByRole("dialog", { name: "View options", exact: true });
  await expect(menu.getByRole("button", { name: "Delete view", exact: true })).toBeEnabled();
  await page.screenshot({ path: info.outputPath("view-dropdown.png") });
  await menu.getByRole("button", { name: "Rename", exact: true }).click();
  await page.getByLabel("View name", { exact: true }).fill("My records"); await page.getByLabel("View name", { exact: true }).press("Enter");
  const renamed = page.getByRole("tab", { name: "My records", exact: true }); await expect(renamed).toBeVisible();
  await renamed.click(); await menu.getByRole("button", { name: "Display as", exact: true }).click();
  await page.getByRole("dialog", { name: "Display as", exact: true }).getByRole("button", { name: "List", exact: true }).click();
  await expect(page.locator(".database-layout-list")).toBeVisible();
  await renamed.click(); await menu.getByRole("button", { name: "Show data source titles", exact: true }).click();
  await expect(page.locator(".database-source-title")).toBeVisible();
  await renamed.click(); await menu.getByRole("button", { name: "Duplicate view", exact: true }).click();
  const copy = page.getByRole("tab", { name: "My records (copy)", exact: true }); await expect(copy).toHaveAttribute("aria-selected", "true");
  await renamed.click({ button: "right" });
  await expect(copy).toHaveAttribute("aria-selected", "true");
  await menu.getByRole("button", { name: "Edit view", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "View settings", exact: true }).getByLabel("View name", { exact: true })).toHaveValue("My records");
  await page.keyboard.press("Escape"); await copy.click(); await menu.getByRole("button", { name: "Delete view", exact: true }).click();
  await expect(copy).toHaveCount(0); await expect(renamed).toHaveAttribute("aria-selected", "true");
  await page.reload(); await expect(page.locator(".database-layout-list")).toBeVisible();
  const saved = await (await request.get(`/api/databases/${db.database.id}`)).json();
  expect(saved.views).toHaveLength(1); expect(saved.dataSources).toHaveLength(1); expect(saved.pages.map((page: any) => page.id)).toEqual([row.id]);
});

test("a conflicting rename keeps the dropdown draft and leaves the newer view unchanged", async ({ page, request }) => {
  const db = await post(request, "/api/databases", { title: "Dropdown conflicts" }), view = db.views[0];
  await page.goto(`/#database/${db.database.id}`); await page.getByRole("tab", { name: "Table", exact: true }).click();
  await page.getByRole("button", { name: "Rename", exact: true }).click();
  await page.getByLabel("View name", { exact: true }).fill("Keep this rename draft");
  expect((await request.put(`/api/database-views/${view.id}`, { data: { baseRevision: view.revision, name: "Other window rename" } })).ok()).toBeTruthy();
  await page.getByRole("button", { name: "Save view", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "Rename view", exact: true }).getByRole("status")).toContainText(/preserved/i);
  await expect(page.getByLabel("View name", { exact: true })).toHaveValue("Keep this rename draft");
  expect((await (await request.get(`/api/databases/${db.database.id}`)).json()).views[0].name).toBe("Other window rename");
});
