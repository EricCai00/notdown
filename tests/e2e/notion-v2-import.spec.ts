import { test, expect } from "@playwright/test";
import { v2Root } from "../unit/notion-v2-fixture";

test("v2 import renders real objects, local attachments and transcript; template execution persists after reload", async ({ page, request }, testInfo) => {
  const seed = await (await request.post("/api/pages", { data: { title: "V2 import start", body: "" } })).json();
  const beforeAssets = (await (await request.get("/api/assets")).json()).assets.length;
  await page.goto(`/#page/${seed.id}`);
  await page.getByRole("button", { name: "Import", exact: true }).click();
  await page.getByRole("button", { name: "Import from Notion API", exact: true }).click();
  await page.getByLabel("Integration token", { exact: true }).fill("test-token-example");
  await page.getByLabel("Page URL or ID", { exact: true }).fill(v2Root);
  await expect(page.getByLabel("Import files, media, covers and icons into Attachments")).toBeChecked();
  await page.getByRole("button", { name: "Preview", exact: true }).click();
  await expect(page.locator("#notion-status")).toContainText("Ready");
  await expect(page.locator("#notion-markdown-source")).toContainText("assets/notion-");
  expect((await (await request.get("/api/assets")).json()).assets.length).toBe(beforeAssets);
  await page.getByRole("button", { name: "Import copies", exact: true }).click();
  await expect(page.locator("#page-title")).toHaveValue("Notion v2 fixture");
  const doc = page.locator(".pm-document[contenteditable=true]");
  const types = await doc.evaluate(element => { const found: string[] = []; (element as any).pmViewDesc.node.descendants((node: any) => found.push(node.type.name)); return found; });
  for (const kind of ["block.mail", "block.custom_block", "block.external_object_instance", "block.meeting_notes", "block.tabs", "block.button", "block.image_block"]) expect(types).toContain(kind);
  await expect(page.locator(".pm-notion-mail")).toContainText("Imported message");
  await expect(page.locator(".pm-notion-reference").first()).toContainText("Custom block reference");
  await expect(page.locator(".pm-unknown").filter({ hasText: "button: configuration unavailable" })).toBeVisible();
  const image = page.locator(".pm-image-block-view img").first();
  await expect(image).toHaveAttribute("src", /assets\/notion-/);
  await expect.poll(() => image.evaluate((element: HTMLImageElement) => element.complete && element.naturalWidth > 0)).toBe(true);
  await page.locator(".pm-object-meeting_notes").getByRole("tab", { name: "Transcript", exact: true }).click();
  await expect(page.locator('.pm-meeting-section[data-section="transcript"]')).toContainText("Complete transcript");
  await page.getByRole("button", { name: "Insert template", exact: true }).click();
  await expect(doc).toContainText("Template content");
  await page.keyboard.press("Control+s");
  await expect(page.locator("#save-status")).toContainText("Saved locally");
  await page.reload();
  await expect(doc).toContainText("Template content");
  await expect(page.locator(".pm-notion-mail")).toContainText("Mail body");
  const saved = await (await request.get(`/api/pages/${new URL(page.url()).hash.slice(6)}`)).json();
  expect(saved.syntax.notionVersion).toBe("v2"); expect(saved.body).toContain("definition-id=");
  await page.locator(".pm-notion-mail").scrollIntoViewIfNeeded();
  await page.screenshot({ path: "test-results/notion-v2-import.png" });
  await page.locator('.main-nav [data-action="attachments"]').click();
  const attachments = page.getByRole("dialog", { name: "Attachments", exact: true });
  await attachments.getByRole("searchbox").fill("photo.png");
  await attachments.locator(".attachment-row").click();
  await expect(attachments.locator(".attachment-info")).toContainText("photo.png");
  await expect(attachments.locator(".attachment-preview img")).toBeVisible();
  await expect.poll(() => attachments.locator(".attachment-preview img").evaluate((image: HTMLImageElement) => image.naturalWidth)).toBe(360);
  await expect(attachments.locator(".attachment-references")).toContainText("Notion v2 fixture");
  await expect(attachments.locator(".attachment-references")).toContainText("Page cover");
  await page.screenshot({ path: testInfo.outputPath("notion-attachments-library.png") });
  await attachments.getByRole("searchbox").fill("report.pdf");
  await attachments.locator(".attachment-row").click();
  await expect(attachments.locator(".attachment-info")).toContainText("report.pdf");
  const files = (await (await request.get("/api/assets")).json()).assets;
  expect(files.filter((asset: any) => asset.path.startsWith("assets/notion-"))).toHaveLength(2);
});

for (const variant of ["notdown", "notion-markdown"] as const) test(`${variant} v2 bookmark edits retain rich captions and respect property boundaries`, async ({page,request}) => {
  await page.route("**/api/bookmarks/resolve", route => route.fulfill({json:{title:"Resolved card",description:"Resolved description",image:"",icon:""}}));
  const note = await (await request.post("/api/pages",{data:{title:"V2 bookmark",body:'<bookmark source="https://example.com/original"><b>Rich</b> caption</bookmark>',syntax:{version:1,variant,notionVersion:"v2",extensions:{}}}})).json();
  await page.goto(`/#page/${note.id}`);
  const block = page.locator(".pm-object-web_bookmark");
  await expect(block).toBeVisible(); await block.hover();
  await block.getByRole("button",{name:"Edit bookmark link"}).click();
  const dialog = page.getByRole("dialog",{name:"Web bookmark",exact:true});
  await dialog.getByLabel("Bookmark URL").fill("https://example.com/changed");
  await dialog.getByLabel("Bookmark URL").press("Enter");
  await expect(dialog).toHaveCount(0);
  await page.keyboard.press("Control+s");
  await expect.poll(async () => (await (await request.get(`/api/pages/${note.id}`)).json()).body).toContain('source="https://example.com/changed"');
  const saved = await (await request.get(`/api/pages/${note.id}`)).json();
  expect(saved.body).toContain("<b>Rich</b> caption");
  if (variant === "notdown") expect(saved.body).toContain('title="Resolved card"');
  else expect(saved.body).not.toContain('title=');
  await page.reload();
  await expect(block).toContainText("Rich caption");
  await expect(block.getByRole("link")).toHaveAttribute("href","https://example.com/changed");
});
