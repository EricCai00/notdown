import { test, expect, type Page } from "@playwright/test";

async function settings(page: Page) {
  await page.locator('#sidebar [data-action="settings"]').click();
  const dialog = page.getByRole("dialog", { name: "Workspace settings", exact: true });
  await dialog.getByRole("navigation", { name: "Settings sections" }).getByRole("button", { name: "Appearance", exact: true }).click();
  return dialog;
}

test("tree starts collapsed, applies depth immediately and reapplies it after reload", async ({ page, request }) => {
  const create = async (title: string, parent: string | null = null) => (await request.post("/api/pages", { data: { title, parent } })).json();
  const root = await create("Depth root"), child = await create("Depth child", root.id), leaf = await create("Depth leaf", child.id);
  const other = await create("Depth other");
  const row = (id: string) => page.locator(`#page-tree [data-page-row="${id}"]`);
  await page.goto(`/#page/${root.id}`);
  await expect(row(root.id).locator(".tree-toggle")).toHaveAttribute("aria-expanded", "false");
  await expect(row(child.id)).toHaveCount(0);
  await row(root.id).hover();
  await row(root.id).locator(".tree-toggle").click();
  await expect(row(child.id)).toBeVisible();
  await expect(row(leaf.id)).toHaveCount(0);
  await row(other.id).locator(".tree-page").click();
  await expect(page.locator("#page-title")).toHaveValue(other.title);
  await expect(row(child.id)).toBeVisible();
  await page.reload();
  await expect(row(child.id)).toHaveCount(0);
  let dialog = await settings(page);
  const depth = () => dialog.getByRole("combobox", { name: "Default expanded levels", exact: true });
  await expect(depth()).toHaveValue("0");
  await depth().selectOption("1");
  await dialog.getByRole("button", { name: "Done", exact: true }).click();
  await expect(row(child.id)).toBeVisible();
  await expect(row(leaf.id)).toHaveCount(0);
  await row(child.id).hover();
  await row(child.id).locator(".tree-toggle").click();
  await expect(row(leaf.id)).toBeVisible();
  await page.reload();
  await expect(row(child.id)).toBeVisible();
  await expect(row(leaf.id)).toHaveCount(0);
  dialog = await settings(page);
  await depth().selectOption("2");
  await expect(row(leaf.id)).toHaveCount(1);
  await depth().selectOption("0");
  await expect(row(child.id)).toHaveCount(0);
  await depth().selectOption("all");
  await dialog.getByRole("button", { name: "Done", exact: true }).click();
  await page.reload();
  await expect(row(leaf.id)).toBeVisible();
});

test("database children switch between records and views with view navigation and live updates", async ({ page, request }, info) => {
  const snapshot = await (await request.post("/api/databases", { data: { title: "Sidebar views" } })).json();
  const source = snapshot.dataSources[0];
  const record = await (await request.post(`/api/data-sources/${source.id}/records`, { data: { baseRevision: source.revision, title: "Sidebar record" } })).json();
  const next = await (await request.post(`/api/databases/${snapshot.database.id}/views`, { data: { baseRevision: snapshot.database.revision, dataSourceId: source.id, name: "Reading list", type: "list" } })).json();
  const table = next.views[0], list = next.views[1];
  await page.goto("/");
  let dialog = await settings(page);
  await dialog.getByRole("combobox", { name: "Database children", exact: true }).selectOption("views");
  await dialog.getByRole("combobox", { name: "Default expanded levels", exact: true }).selectOption("1");
  await dialog.getByRole("combobox", { name: "Default expanded levels", exact: true }).scrollIntoViewIfNeeded();
  await dialog.screenshot({ path: info.outputPath("sidebar-settings.png") });
  await dialog.getByRole("button", { name: "Done", exact: true }).click();
  const viewRow = (id: string) => page.locator(`#page-tree [data-database-view-row="${id}"]`);
  await expect(viewRow(table.id)).toBeVisible();
  await expect(viewRow(list.id)).toBeVisible();
  await expect(page.locator(`#page-tree [data-page-row="${record.id}"]`)).toHaveCount(0);
  await viewRow(list.id).getByRole("button").click();
  await expect(page.getByRole("tab", { name: "Reading list", exact: true })).toHaveAttribute("aria-selected", "true");
  await expect(page).toHaveURL(new RegExp(`view=${list.id}$`));
  await expect(viewRow(list.id)).toHaveClass(/active/);
  await page.reload();
  await expect(page.getByRole("tab", { name: "Reading list", exact: true })).toHaveAttribute("aria-selected", "true");
  await page.getByRole("tab", { name: "Table", exact: true }).click();
  await expect(viewRow(table.id)).toHaveClass(/active/);
  await expect(page).toHaveURL(new RegExp(`view=${table.id}$`));
  await page.reload();
  await expect(page.getByRole("tab", { name: "Table", exact: true })).toHaveAttribute("aria-selected", "true");
  await page.getByRole("button", { name: "View settings", exact: true }).click();
  const viewSettings = page.getByRole("dialog", { name: "View settings", exact: true });
  await viewSettings.getByLabel("View name", { exact: true }).fill("Renamed table");
  await viewSettings.getByRole("button", { name: "Save view", exact: true }).click();
  await expect(viewRow(table.id)).toHaveText("Renamed table");
  await page.getByRole("button", { name: "New view", exact: true }).click();
  await page.getByRole("dialog", { name: "New view", exact: true }).getByRole("button", { name: "Gallery", exact: true }).click();
  await page.getByRole("button", { name: "Create view", exact: true }).click();
  await expect(page.locator('#page-tree [data-open-database="' + snapshot.database.id + '"][data-database-view]').filter({ hasText: "Gallery" })).toBeVisible();
  await page.screenshot({ path: info.outputPath("sidebar-views.png") });
  dialog = await settings(page);
  await expect(dialog.getByRole("combobox", { name: "Database children", exact: true })).toHaveValue("views");
  await dialog.getByRole("combobox", { name: "Database children", exact: true }).selectOption("pages");
  await dialog.getByRole("button", { name: "Done", exact: true }).click();
  await expect(page.locator(`#page-tree [data-page-row="${record.id}"]`)).toBeVisible();
  await expect(viewRow(table.id)).toHaveCount(0);
  expect((await (await request.get(`/api/pages/${record.id}`)).json()).parent).toBe(snapshot.hostPage.id);
});

test("view loading failures can be retried without changing the database", async ({ page, request }) => {
  const snapshot = await (await request.post("/api/databases", { data: { title: "Retry sidebar views" } })).json();
  const path = `**/api/databases/${snapshot.database.id}`;
  let fail = true;
  await page.route(path, route => fail ? route.fulfill({ status: 503, json: { error: "Temporary failure" } }) : route.continue());
  await page.addInitScript(() => localStorage.setItem("notdown-sidebar-tree", JSON.stringify({ databaseChildren: "views", expandDepth: 0 })));
  await page.goto("/");
  const row = page.locator(`#page-tree [data-page-row="${snapshot.hostPage.id}"]`);
  await row.hover();
  await row.locator(".tree-toggle").click();
  const retry = page.locator(`[data-retry-sidebar-views="${snapshot.database.id}"]`);
  await expect(retry).toBeVisible();
  fail = false;
  await retry.click();
  await expect(page.locator(`[data-database-view-row="${snapshot.views[0].id}"]`)).toBeVisible();
  expect(await (await request.get(`/api/databases/${snapshot.database.id}`)).json()).toEqual(snapshot);
});
