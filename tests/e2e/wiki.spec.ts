import { selectWikiView } from "./wiki-ui-helper";
import { test, expect } from "@playwright/test";

test("page conversion keeps Home editable, lists the wiki, and Undo preserves the tree", async ({ page, request }, info) => {
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  const home = await (await request.post("/api/pages", { data: { title: "Knowledge wiki E2E", body: "Original home", syntax: { version: 1, variant: "notdown", extensions: {} } } })).json();
  const child = await (await request.post("/api/pages", { data: { title: "Guide wiki E2E", parent: home.id, body: "Guide body" } })).json();
  await request.post("/api/pages", { data: { title: "Nested wiki E2E", parent: child.id, body: "Nested body" } });
  await page.goto(`/#page/${home.id}`);
  await page.locator(".pm-document").fill("Pending home before conversion");
  await page.locator("#main").click({ position: { x: 5, y: 5 } });
  await page.locator("#page-options > summary").click();
  await page.getByRole("menuitem", { name: "Turn into wiki", exact: true }).click();
  await expect(page.locator("#page-title")).toHaveValue(home.title);
  await expect(page.getByRole("navigation", { name: "Wiki views" })).toBeVisible();
  await expect(page.locator(".pm-document")).toContainText("Pending home before conversion");
  await selectWikiView(page, "All pages");
  await expect(page.getByRole("button", { name: `Open ${child.title}`, exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Open Nested wiki E2E", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Data sources", exact: true })).toHaveCount(0);
  await page.locator(".wiki-view-trigger").click();
  await page.getByRole("button", { name: "New view", exact: true }).click();
  await expect(page.getByRole("button", { name: "Source", exact: true })).toHaveCount(0);
  await page.keyboard.press("Escape");
  await selectWikiView(page, "Home");
  await expect(page.locator("#page-title")).toHaveValue(home.title);
  await page.locator(".pm-document").fill("Edited wiki Home");
  await page.getByRole("button", { name: "Databases", exact: true }).first().click();
  await expect(page.locator(".database-list")).toContainText(home.title);
  await expect(page.locator(".database-list")).toContainText("Wiki · Home and page views");
  await page.locator(`[data-db-open="${home.id}"]`).click();
  await expect(page.locator(".pm-document")).toContainText("Edited wiki Home");
  await page.reload();
  await expect(page.getByRole("navigation", { name: "Wiki views" })).toBeVisible();
  await page.screenshot({ path: info.outputPath("wiki-home.png"), fullPage: true });
  await page.locator("#page-options > summary").click();
  await page.getByRole("menuitem", { name: "Undo wiki", exact: true }).click();
  await expect(page.getByRole("navigation", { name: "Wiki views" })).toHaveCount(0);
  await expect(page.locator(".pm-document")).toContainText("Edited wiki Home");
  const savedChild = await (await request.get(`/api/pages/${child.id}`)).json();
  expect(savedChild.parent).toBe(home.id); expect(savedChild.dataSourceId).toBeUndefined();
  expect((await (await request.get("/api/databases")).json()).some((db: any) => db.id === home.id)).toBeFalsy();
  expect(errors).toEqual([]);
});

test("slash Wiki creates one child wiki and a persistent official database reference", async ({ page, request }, info) => {
  const parent = await (await request.post("/api/pages", { data: { title: "Slash wiki parent", body: "", syntax: { version: 1, variant: "notdown", extensions: {} } } })).json();
  await page.goto(`/#page/${parent.id}`);
  await page.locator(".pm-document").click(); await page.keyboard.type("/wiki");
  await page.locator('.inline-slash [data-insert="wiki"]').click();
  await expect(page.locator("#page-title")).toHaveValue("New wiki");
  await expect(page.getByRole("navigation", { name: "Wiki views" })).toBeVisible();
  const databases = await (await request.get("/api/databases")).json(), wiki = databases.find((db: any) => db.kind === "wiki" && db.parent === parent.id);
  expect(wiki).toBeTruthy(); expect(wiki.dataSourceIds).toHaveLength(1);
  const source = await (await request.get(`/api/pages/${parent.id}`)).json();
  expect(source.body).toContain('wiki="true"'); expect(source.body).toContain(`#page/${wiki.pageId}`); expect(source.body).not.toContain("/wiki");
  await page.reload(); await expect(page.locator("#page-title")).toHaveValue("New wiki");
  await selectWikiView(page, "All pages");
  await page.screenshot({ path: info.outputPath("wiki-all-pages.png"), fullPage: true });
  await page.locator(".database-more-menu > summary").click();
  await page.getByRole("button", { name: "Undo wiki", exact: true }).click();
  await expect(page.getByRole("navigation", { name: "Wiki views" })).toHaveCount(0);
  await expect(page.locator("#page-title")).toHaveValue("New wiki");
});
