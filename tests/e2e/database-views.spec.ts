import { test, expect } from "@playwright/test";
import { createBlockDatabase } from "./database-fixture";

test("Notion-style view picker, shared records, board movement, settings and calendar", async ({ page, request }, info) => {
  test.setTimeout(60000);
  const data = await createBlockDatabase(request);
  const dateId = crypto.randomUUID();
  const schema = await (await request.put(`/api/data-sources/${data.schema.id}`, { data: { baseRevision: data.schema.revision, properties: [...data.schema.properties, { id: dateId, key: "due", name: "Due", type: "date" }] } })).json();
  const record = data.records[0];
  const today = new Date(); const day = `${today.getFullYear()}-${String(today.getMonth()+1).padStart(2,"0")}-${String(today.getDate()).padStart(2,"0")}`;
  expect((await request.put(`/api/data-sources/${schema.id}/records/${record.id}`, { data: { baseRevision: record.revision, schemaRevision: schema.revision, propertyId: dateId, value: { start: day, end: null } } })).ok()).toBeTruthy();
  await page.goto(`/#database/${data.database.id}`);
  const create = async (type: string) => {
    await page.getByRole("button", { name: "New view", exact: true }).click();
    const picker = page.getByRole("dialog", { name: "New view" });
    await expect(picker).toBeVisible();
    if (type === "List") await page.screenshot({ path: info.outputPath("view-picker.png") });
    await picker.getByRole("button", { name: type, exact: true }).click();
    await page.getByRole("button", { name: "Create view", exact: true }).click();
    await expect(page.getByRole("tab", { name: type, exact: true })).toHaveAttribute("aria-selected", "true");
  };
  await create("List");
  await expect(page.locator(".database-layout-list .database-record-card")).toHaveCount(15);
  await create("Gallery");
  await expect(page.locator(".database-layout-gallery .database-record-card")).toHaveCount(15);
  await page.screenshot({ path: info.outputPath("gallery.png"), fullPage: true });
  await page.getByRole("button", { name: "Open Text", exact: true }).click();
  await expect(page.locator(".database-peek-mount")).toBeVisible();
  await page.getByRole("button", { name: "Close record", exact: true }).click();
  await create("Board");
  const card = page.locator(`.database-layout-board [data-page-id="${record.id}"]`);
  await card.dragTo(page.locator('.database-card-group[data-group="no"]'), { targetPosition: { x: 30, y: 20 } });
  await expect.poll(async () => (await (await request.get(`/api/pages/${record.id}`)).json()).properties.inMarkdown).toBe("no");
  await expect(page.locator(`.database-card-group[data-group="no"] [data-page-id="${record.id}"]`)).toBeVisible();
  await page.screenshot({ path: info.outputPath("board.png"), fullPage: true });
  await page.getByRole("button", { name: "View settings", exact: true }).click();
  await page.getByRole("dialog", { name: "View settings", exact: true }).getByRole("button", { name: "Filter", exact: true }).click();
  const settings = page.getByRole("dialog", { name: "Filter", exact: true });
  await settings.getByLabel("Filter property", { exact: true }).selectOption({ label: "Name" });
  await settings.getByLabel("Contains", { exact: true }).fill("Text");
  await settings.getByRole("button", { name: "Add filter" }).click();
  await settings.getByLabel("Filter property", { exact: true }).nth(1).selectOption({ label: "Name" });
  await settings.getByLabel("Contains", { exact: true }).nth(1).fill("Image");
  await settings.getByRole("combobox", { name: "Match", exact: true }).selectOption("or");
  await settings.getByRole("button", { name: "Close", exact: true }).click();
  await expect(page.locator(".database-layout-board .database-record-card")).toHaveCount(2);
  await create("Calendar");
  await expect(page.locator(`.database-calendar-day[data-date="${day}"] [data-page-id="${record.id}"]`)).toBeVisible();
  const target = page.locator(".database-calendar-day").filter({ hasNot: page.locator(`[data-page-id="${record.id}"]`) }).nth(10);
  const targetDate = await target.getAttribute("data-date");
  await page.locator(`.database-calendar-day [data-page-id="${record.id}"]`).dragTo(target);
  await expect.poll(async () => (await (await request.get(`/api/pages/${record.id}`)).json()).properties.due.start).toBe(targetDate);
  await page.screenshot({ path: info.outputPath("calendar.png"), fullPage: true });
  await page.reload();
  await expect(page.getByRole("tab", { name: "Calendar", exact: true })).toHaveAttribute("aria-selected", "true");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "More database views", exact: true }).click();
  await page.getByRole("menuitemradio", { name: "Gallery", exact: true }).click();
  await expect(page.locator(".database-layout-gallery .database-record-card")).toHaveCount(15);
  await page.screenshot({ path: info.outputPath("gallery-narrow.png"), fullPage: true });
});

test("empty databases create required fields and new layout conflicts retain drafts", async ({ page, request }) => {
  test.setTimeout(60000);
  const initial = await (await request.post("/api/databases", { data: { title: "Native views" } })).json();
  await page.goto(`/#database/${initial.database.id}`);
  for (const type of ["Board", "Calendar"]) {
    await page.getByRole("button", { name: "New view", exact: true }).click();
    await page.getByRole("dialog", { name: "New view" }).getByRole("button", { name: type, exact: true }).click();
    await page.getByRole("button", { name: "Create view", exact: true }).click();
    await expect(page.getByRole("tab", { name: type, exact: true })).toHaveAttribute("aria-selected", "true");
  }
  const snapshot = await (await request.get(`/api/databases/${initial.database.id}`)).json();
  expect(snapshot.dataSources[0].properties.map((field: any) => field.type)).toEqual(["title", "status", "date"]);
  await page.getByRole("tab", { name: "Board", exact: true }).click();
  await page.getByRole("button", { name: "New page in Not started", exact: true }).click();
  await page.getByLabel("Row title").fill("Draft card");
  await page.getByRole("button", { name: "Create row", exact: true }).click();
  const card = page.locator(".database-record-card").filter({ has: page.getByRole("button", { name: "Open Draft card", exact: true }) });
  await expect(card).toBeVisible();
  const after = await (await request.get(`/api/databases/${initial.database.id}`)).json(), record = after.pages[0];
  const changed = await request.put(`/api/pages/${record.id}`, { data: { baseRevision: record.revision, body: "Changed from another window" } }); expect(changed.ok()).toBeTruthy();
  const status = after.dataSources[0].properties.find((field: any) => field.type === "status");
  await card.dragTo(page.locator(`.database-card-group[data-group="${status.options[1].id}"]`), { targetPosition: { x: 30, y: 20 } });
  await expect(page.locator(".database-message").first()).toContainText("Edits remain in this tab");
  const preserved = await (await request.get(`/api/pages/${record.id}`)).json();
  expect(preserved.body).toBe("Changed from another window"); expect(preserved.properties[status.key]).toBe(status.options[0].id);
  await page.getByRole("tab", { name: "Calendar", exact: true }).click();
  await expect(page.getByRole("tab", { name: "Board", exact: true })).toHaveAttribute("aria-selected", "true");
});
