import { test, expect, type Page, type APIRequestContext } from "@playwright/test";
import { readFile } from "node:fs/promises";

async function open(page: Page, request: APIRequestContext, variant = "notdown") {
  const image = await (await request.post("/api/assets", { data: { name: "image.png", contentType: "image/png", data: (await readFile(new URL("../../docs/fixtures/typora-comparison-image.png", import.meta.url))).toString("base64") } })).json();
  const source = `![Initial caption](${image.path}${variant === "notdown" ? ' "Kept title"){alt="Alternative" custom="width=999 keep" width="400"}' : ")"}\n\nTail`;
  const note = await (await request.post("/api/pages", { data: { title: "Image controls", body: source, syntax: { version: 1, variant, extensions: {} } } })).json();
  await page.goto(`/#page/${note.id}`);
  await expect(page.locator(".pm-image-block-view")).toBeVisible();
  await expect.poll(() => page.locator(".pm-image-content").evaluate((el: HTMLImageElement) => el.naturalWidth)).toBeGreaterThan(0);
  return { ...note, imagePath: image.path, source };
}

test("image toolbar alignment, caption, resizing and undo persist across source/page and reload", async ({ page, request }) => {
  const note = await open(page, request), block = page.locator(".pm-image-block-view"), shell = block.locator(".pm-image-shell");
  await block.hover();
  await expect(block.getByRole("toolbar", { name: "Image controls" })).toBeVisible();
  await expect(block.locator(".pm-image-toolbar > button, .pm-image-toolbar > a")).toHaveCount(6);
  await expect(block.getByRole("button", { name: /comment/i })).toHaveCount(0);
  await block.getByRole("button", { name: "Image alignment" }).click();
  await block.getByRole("menuitem", { name: "Align right" }).click();
  await expect(block).toHaveAttribute("data-align", "right");
  const handle = block.getByRole("button", { name: "Resize image from right" });
  const before = (await shell.boundingBox())!.width;
  const box = (await handle.boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 - 60, box.y + box.height / 2, { steps: 6 }); await page.mouse.up();
  await expect.poll(async () => (await shell.boundingBox())!.width).toBeCloseTo(before - 60, 0);
  await page.keyboard.press("Control+z");
  await expect.poll(async () => (await shell.boundingBox())!.width).toBeCloseTo(before, 0);
  await page.keyboard.press("Control+Shift+z");
  await expect.poll(async () => (await shell.boundingBox())!.width).toBeCloseTo(before - 60, 0);
  await block.hover(); await block.getByRole("button", { name: "Edit caption" }).click();
  const dialog = page.getByRole("dialog", { name: "Image caption", exact: true });
  await dialog.getByLabel("Caption", { exact: true }).fill("Updated caption");
  await dialog.getByRole("button", { name: "Save", exact: true }).click();
  await expect(block.locator(".pm-image-caption")).toHaveText("Updated caption");
  await page.keyboard.press("Control+s");
  await expect.poll(async () => (await (await request.get(`/api/pages/${note.id}`)).json()).body).toContain('align="right"');
  const saved = (await (await request.get(`/api/pages/${note.id}`)).json()).body;
  expect(saved).toContain('custom="width=999 keep"'); expect(saved).toContain('"Kept title"'); expect(saved).toContain('width="340"');
  await page.locator('[data-mode="source"]').click(); await page.locator('[data-mode="document"]').click();
  await expect(block.locator(".pm-image-caption")).toHaveText("Updated caption");
  await page.reload(); await expect(block).toHaveAttribute("data-align", "right");
  await block.hover(); await block.screenshot({ path: "test-results/image-toolbar.png" });
});

test("crop is reversible, retains the original resource, and expand/download/more work", async ({ page, request }) => {
  const note = await open(page, request), block = page.locator(".pm-image-block-view");
  await block.hover(); await block.getByRole("button", { name: "Crop image", exact: true }).click();
  const crop = page.getByRole("dialog", { name: "Crop image", exact: true });
  await crop.getByRole("button", { name: "Square", exact: true }).click();
  await crop.getByLabel("Crop width", { exact: true }).fill("60"); await crop.getByLabel("Crop width", { exact: true }).press("Tab");
  await crop.getByLabel("Crop height", { exact: true }).fill("60"); await crop.getByLabel("Crop height", { exact: true }).press("Tab");
  const dialogBounds = (await crop.boundingBox())!, stageBounds = (await crop.locator(".pm-image-crop-stage").boundingBox())!;
  expect(stageBounds.x + stageBounds.width).toBeLessThanOrEqual(dialogBounds.x + dialogBounds.width);
  await crop.screenshot({ path: "test-results/image-crop.png" });
  await crop.getByRole("button", { name: "Apply crop", exact: true }).click();
  await expect(block.locator(".pm-image-viewport")).toHaveAttribute("style", /aspect-ratio/);
  await expect(block.locator(".pm-image-content")).toHaveAttribute("src", note.imagePath);
  await page.keyboard.press("Control+s");
  await expect.poll(async () => (await (await request.get(`/api/pages/${note.id}`)).json()).body).toContain('crop="');
  await page.reload(); await expect(block.locator(".pm-image-viewport")).toHaveAttribute("style", /aspect-ratio/);
  await block.hover(); await block.getByRole("button", { name: "Expand image" }).click();
  const expanded = page.getByRole("dialog", { name: "Expanded image", exact: true });
  await expect(expanded.getByRole("img")).toHaveAttribute("src", note.imagePath);
  await expanded.getByRole("button", { name: "Zoom in", exact: true }).click();
  await expect(expanded.getByRole("img")).toHaveAttribute("style", /scale\(1.25\)/);
  await page.keyboard.press("Escape"); await expect(expanded).toHaveCount(0);
  const download = page.waitForEvent("download"); await block.getByRole("link", { name: "Download image" }).click();
  expect((await download).suggestedFilename()).toMatch(/\.png$/);
  await block.getByRole("button", { name: "More image actions" }).click();
  await block.getByRole("menuitem", { name: "Reset crop", exact: true }).click();
  await expect(block.locator(".pm-image-viewport")).not.toHaveAttribute("style", /aspect-ratio/);
  await page.keyboard.press("Control+z"); await expect(block.locator(".pm-image-viewport")).toHaveAttribute("style", /aspect-ratio/);
  await block.hover(); await block.getByRole("button", { name: "Edit caption" }).click();
  const caption = page.getByRole("dialog", { name: "Image caption", exact: true });
  await caption.getByLabel("Caption", { exact: true }).fill(""); await caption.getByRole("button", { name: "Save", exact: true }).click();
  await expect(block.locator(".pm-image-caption")).toBeHidden();
  await page.keyboard.press("Control+s"); await page.reload();
  await expect(block.locator(".pm-image-viewport")).toHaveAttribute("style", /aspect-ratio/);
});

