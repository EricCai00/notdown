test("image more actions and left resize support cancellation, keyboard operation and undo", async ({ page, request }) => {
  const note = await open(page, request), block = page.locator(".pm-image-block-view"), shell = block.locator(".pm-image-shell");
  await block.hover();
  const left = block.getByRole("button", { name: "Resize image from left" });
  const box = (await left.boundingBox())!, width = (await shell.boundingBox())!.width;
  await page.mouse.move(box.x + 4, box.y + 20); await page.mouse.down(); await page.mouse.move(box.x - 25, box.y + 20);
  await page.keyboard.press("Escape"); await page.mouse.up();
  await expect.poll(async () => (await shell.boundingBox())!.width).toBeCloseTo(width, 0);
  await left.focus(); await left.press("ArrowLeft");
  await expect.poll(async () => (await shell.boundingBox())!.width).toBeCloseTo(width + 10, 0);
  await block.getByRole("button", { name: "Crop image", exact: true }).click();
  const crop = page.getByRole("dialog", { name: "Crop image", exact: true });
  await crop.getByRole("button", { name: "Square", exact: true }).click();
  await crop.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(block.locator(".pm-image-viewport")).not.toHaveAttribute("style", /aspect-ratio/);
  await block.hover(); await block.getByRole("button", { name: "More image actions" }).click();
  await block.getByRole("menuitem", { name: "Replace image…", exact: true }).click();
  const replace = page.getByRole("dialog", { name: "Replace image", exact: true });
  await replace.getByLabel("Image URL", { exact: true }).fill(note.imagePath + "?replacement=1");
  await replace.getByRole("button", { name: "Save", exact: true }).click();
  await expect(block.locator(".pm-image-content")).toHaveAttribute("src", note.imagePath + "?replacement=1");
  await page.evaluate(() => Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText: async (value: string) => { document.body.dataset.copiedImage = value; } } }));
  await block.hover(); await block.getByRole("button", { name: "More image actions" }).click();
  await block.getByRole("menuitem", { name: "Copy image link", exact: true }).click();
  await expect(page.locator("body")).toHaveAttribute("data-copied-image", new RegExp(note.imagePath + "\\?replacement=1$"));
  await block.hover(); await block.getByRole("button", { name: "More image actions" }).click();
  await block.getByRole("menuitem", { name: "Original size", exact: true }).click();
  await page.keyboard.press("Control+s");
  await expect.poll(async () => (await (await request.get(`/api/pages/${note.id}`)).json()).body).not.toMatch(/\swidth="/);
  await block.hover(); await block.getByRole("button", { name: "More image actions" }).click();
  await block.getByRole("menuitem", { name: "Delete image", exact: true }).click();
  await expect(block).toHaveCount(0); await page.keyboard.press("Control+z"); await expect(block).toHaveCount(1);
});
