test("rightward map styles follow actual heading levels and body uses only a baseline", async ({ page, request }) => {
  const note = await create(request, "# H1\n\n## H2\n\n### H3\n\n#### H4\n\n##### H5\n\n###### H6\n\nBody text");
  await page.goto(`/#page/${note.id}`); await mode(page, "mindmap");
  const map = page.locator(".mindmap-view");
  await map.locator('[data-map-preset="expanded"]').click();
  const styles = await map.locator(".mindmap-heading").evaluateAll(nodes => nodes.map(node => {
    const css = getComputedStyle(node), label = getComputedStyle(node.querySelector(".mindmap-label")!);
    return { level: node.getAttribute("data-heading-level"), border: css.borderTopColor, background: css.backgroundColor, font: parseFloat(label.fontSize) };
  }));
  expect(styles.map(style => style.level)).toEqual(["1", "2", "3", "4", "5", "6"]);
  expect(styles[0].border).toBe(styles[1].border);
  expect(styles[2].border).not.toBe(styles[1].border);
  expect(styles[3].border).not.toBe(styles[2].border);
  expect(styles[3]).toEqual({ ...styles[4], level: "4" });
  expect(styles[3].font).toBeLessThan(styles[2].font);
  expect(styles[2].font).toBeLessThan(styles[1].font);
  await expect(map.locator(".mindmap-paragraph")).toHaveCSS("border-top-style", "none");
  await expect(map.locator(".mindmap-paragraph")).toHaveCSS("border-bottom-style", "solid");
  const rightward = await map.evaluate(host => [...host.querySelectorAll<HTMLElement>(".mindmap-branch")].every(branch => {
    const parent = host.querySelector(`[data-map-id="${branch.dataset.parent}"]`)!.getBoundingClientRect();
    const child = branch.querySelector(":scope > .mindmap-topic")!.getBoundingClientRect();
    return child.left > parent.right;
  }));
  expect(rightward).toBe(true);
});

